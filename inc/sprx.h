/**
 *  \file sprx.h
 *  \brief SPRX: main sprite path of this fork (per-part tile / flip / palette frames, SPRJ resource)
 *
 * [V1] SPRX : main sprite path of this fork (not part of upstream SGDK), built into the default sprite engine.
 * Was ext/sprite_eng_ext.h (still available as a forwarding header).
 *
 * An "extended frame" is a standard AnimationFrame followed, right after its
 * frameVDPSprites[numSprite] array, by a FrameVDPSpriteExt[numSprite] array.
 * Each entry gives, for the matching VDP sprite, its tile offset (relative to the
 * sprite VRAM tile index), its own H/V flip and a palette offset.
 * The standard part of the frame (offsets, size) is left untouched so visibility
 * computation of the sprite engine works as is.
 *
 * Sprites using extended frames must have the SPR_FLAG_EXT_FRAME flag:
 * always create / set them with SPRX_addSprite(..) or SPRX_setDefinition(..).
 *
 * Data is generated by the rescomp-cs SPRJ resource (JSON sprite format).
 */

#ifndef _SPRX_H_
#define _SPRX_H_

#include "config.h"
#include "types.h"
#include "sprite_eng.h"
#include "vram.h"
#include "vdp_spr.h"
#include "dma.h"

#if (MODULE_SPRITE_EXT != 0)

/**
 *  \brief
 *      Extra information for one VDP sprite of an extended frame.
 *
 *  \param attr
 *      bit 0-10  : tile offset from the sprite VRAM tile index<br>
 *      bit 11    : H flip of this part (XORed with sprite H flip)<br>
 *      bit 12    : V flip of this part (XORed with sprite V flip)<br>
 *      bit 13-14 : palette offset (added to sprite palette, modulo 4)<br>
 *      bit 15    : unused (0)
 */
typedef struct
{
    u16 attr;
} FrameVDPSpriteExt;

/**
 *  \brief
 *      Get the FrameVDPSpriteExt array of an extended frame.
 */
#define SPRX_FRAME_EXT(frame)   ((const FrameVDPSpriteExt*) &((frame)->frameVDPSprites[(frame)->numSprite & 0x7F]))

/**
 *  \brief
 *      VRAM mode chosen at conversion time (SPRJ resource).
 */
typedef enum
{
    SPRX_RESIDENT = 0,      /**< all part tiles stay in VRAM (loaded once with SPRX_loadResident(..)), shared by all sprites */
    SPRX_TRANSFER = 1       /**< frame tiles are uploaded (DMA) on each frame change, maxNumTile per sprite */
} SprxVramMode;

/**
 *  \brief
 *      One collision / hit box of a frame (JSON "boxes").
 *      Coordinates are relative to the sprite pivot (canvas center in the editor), not flipped.
 */
typedef struct
{
    u8 kind;        /**< box kind (SprxBoxKind enum generated in the resource header) */
    u8 index;       /**< index of the box among the boxes of the same kind in this frame */
    s8 x;           /**< left, relative to pivot */
    s8 y;           /**< top, relative to pivot */
    u8 w;
    u8 h;
} SprxBox;

/**
 *  \brief
 *      Box list of a frame, stored in AnimationFrame.collision (field unused by the sprite engine).
 *      Boxes are sorted by kind then index.
 */
typedef struct
{
    u16 numBox;
    SprxBox boxes[];
} SprxBoxList;

/**
 *  \brief
 *      Simple rectangle (result of SPRX_getBox(..)).
 */
typedef struct
{
    s16 x;
    s16 y;
    s16 w;
    s16 h;
} SprxRect;

/**
 *  \brief
 *      SPRJ resource main structure.
 *
 *  \param def
 *      sprite definition (extended frames)
 *  \param vramMode
 *      SprxVramMode
 *  \param vramTiles
 *      RESIDENT: number of tiles of residentTiles / TRANSFER: max number of tile of a frame
 *  \param residentTiles
 *      RESIDENT: all unique part tiles (to load once) / TRANSFER: NULL
 *  \param pivotX
 *      pivot X position inside the sprite bounding box
 *  \param pivotY
 *      pivot Y position inside the sprite bounding box
 */
typedef struct
{
    const SpriteDefinition* def;
    u16 vramMode;
    u16 vramTiles;
    const TileSet* residentTiles;
    s16 pivotX;
    s16 pivotY;
} SprxInfo;


/**
 *  \brief
 *      Allocate (from region) and load the resident tiles of a RESIDENT SPRJ resource.
 *
 *  \return VRAM tile index to pass to SPRX_addSprite(..) / SPRX_setDefinition(..), or -1 on failure
 *          (not enough VRAM in region, or not a RESIDENT resource).
 */
s16 SPRX_loadResident(const SprxInfo* info, VRAMRegion* region, TransferMethod tm);
/**
 *  \brief
 *      Same as SPRX_loadResident(..) but load at a given VRAM tile index (no allocation).
 */
bool SPRX_loadResidentAt(const SprxInfo* info, u16 index, TransferMethod tm);

/**
 *  \brief
 *      Add a sprite using a SPRJ resource.
 *
 *  \param x, y
 *      pivot position on screen
 *  \param attribut
 *      priority / palette / flip (TILE_ATTR(..)), tile index part is ignored
 *  \param vramIndex
 *      RESIDENT: value returned by SPRX_loadResident(..) (can be shared by any number of sprites)<br>
 *      TRANSFER: VRAM area of info->vramTiles tiles (VRAM_alloc(..)) reserved for this sprite
 *  \param flag
 *      extra SPR_FLAG_xxx (SPR_FLAG_EXT_FRAME, SPR_FLAG_AUTO_VISIBILITY and, for TRANSFER, SPR_FLAG_AUTO_TILE_UPLOAD are always set)
 */
Sprite* SPRX_addSprite(const SprxInfo* info, s16 x, s16 y, u16 attribut, u16 vramIndex, u16 flag);
/**
 *  \brief
 *      Set a SPRJ resource on an already allocated sprite (sprite pool usage).
 */
bool SPRX_setDefinition(Sprite* sprite, const SprxInfo* info, u16 vramIndex);
/**
 *  \brief
 *      Remove extended frame mode from a sprite (call it before using a standard SpriteDefinition again on that sprite).
 */
void SPRX_detach(Sprite* sprite);
/**
 *  \brief
 *      Set sprite position from its pivot position.
 */
void SPRX_setPosition(Sprite* sprite, const SprxInfo* info, s16 x, s16 y);

/**
 *  \brief
 *      Box list of the current frame (NULL if none).
 */
const SprxBoxList* SPRX_getBoxes(const Sprite* sprite);
/**
 *  \brief
 *      Get box #index of the given kind for the current frame, relative to pivot with sprite H/V flip applied.
 *
 *  \return FALSE if no such box
 */
bool SPRX_getBox(const Sprite* sprite, u16 kind, u16 index, SprxRect* out);

/**
 *  \brief
 *      Internal: fill hardware sprites for an extended frame (called from SPR_update()).
 */
VDPSprite* SPRX_fillVDPSprites(const Sprite* sprite, VDPSprite* vdpSprite, u8* vdpSpriteInd);

#endif // MODULE_SPRITE_EXT

#endif // _SPRX_H_
